export type Key = keyof typeof D;

export function translate(lang: Lang, key: Key): string {
  const [ru, uz] = D[key];
  if (lang === 'ru') return ru;
  if (lang === 'uz') return uz;
  return uzLatinToCyrillic(uz);
}

export const LangContext = createContext<Lang>('ru');

export function useT() {
  const lang = useContext(LangContext);
  return Object.assign((key: Key) => translate(lang, key), {
    lang,
    /** Строка с подстановками {0}, {1}: цифры в фигурных скобках переживают транслитерацию. */
    f: (key: Key, ...args: (string | number)[]) => translate(lang, key).replace(/\{(\d)\}/g, (_, i: string) => String(args[Number(i)] ?? '')),
  });
}

